"""Real WAV reads and tamper cases, always using isolated scratch directories."""
import hashlib
from pathlib import Path
import tempfile
import unittest

import numpy as np

from this_voice_thing.core.audio_project_media import ProjectMedia
from this_voice_thing.core.soundscape.assets import AssetLibrary


class ProjectMediaTests(unittest.TestCase):
    def setUp(self):
        self.folder = tempfile.TemporaryDirectory()
        self.root = Path(self.folder.name)
        self.sounds = AssetLibrary(str(self.root))
        self.media = ProjectMedia(self.root, self.sounds)
        self.audio = np.sin(2 * np.pi * 220 * np.arange(4800) / 48000).astype(np.float32) * 0.1

    def tearDown(self):
        self.folder.cleanup()

    def test_voice_take_content_addressed_and_reopenable(self):
        voice_id = self.media.import_voice_take(self.audio, 48000)
        self.assertTrue(voice_id.startswith("voice_"))
        self.assertEqual(self.media.import_voice_take(self.audio, 48000), voice_id)
        fresh = ProjectMedia(self.root, AssetLibrary(str(self.root)))
        pcm, rate = fresh.resolve(voice_id)
        self.assertEqual((len(pcm), rate), (4800, 48000))
        self.assertEqual(pcm.shape, (4800, 2))
        self.assertTrue(np.max(np.abs(pcm)) > 0.05)

    def test_generated_voice_has_bound_local_claim_but_import_stays_unknown(self):
        imported = self.media.import_voice_take(self.audio, 48000)
        self.assertIsNone(self.media.read_voice_origin(imported))
        # A different actual render is independently captured by the Studio TTS
        # code path. No model identity or private text is inferred.
        generated_audio = self.audio * 0.8
        generated = self.media.import_generated_voice_take(generated_audio, 48000)
        record = self.media.read_voice_origin(generated)
        self.assertEqual(record["origin"], "ai_generated")
        self.assertEqual(record["engine"], "studio_tts_worker")
        self.assertEqual(record["media_sha256"], generated[len("voice_"):])
        self.assertEqual(record["evidence_status"], "unsigned_local_generation_event")
        self.assertNotIn("prompt", str(record))
        self.assertNotIn("voice_id", str(record))
        reopened = ProjectMedia(self.root, AssetLibrary(str(self.root)))
        self.assertEqual(reopened.read_voice_origin(generated), record)
        self.assertEqual(reopened.import_generated_voice_take(generated_audio, 48000), generated)

    def test_import_then_generate_identical_wav_keeps_origin_unknown(self):
        imported = self.media.import_voice_take(self.audio, 48000)
        generated = self.media.import_generated_voice_take(self.audio, 48000)
        self.assertEqual(generated, imported)
        self.assertIsNone(self.media.read_voice_origin(imported))
        digest = imported[len("voice_"):]
        self.assertTrue((self.media.voice_root / (digest + ".origin-ambiguous")).is_file())
        self.assertFalse((self.media.voice_root / (digest + ".origin.json")).exists())
        # The source media remains usable and byte-verified.
        pcm, rate = self.media.resolve(generated)
        self.assertEqual((len(pcm), rate), (len(self.audio), 48000))

    def test_generate_then_import_identical_wav_quarantines_origin_claim(self):
        generated = self.media.import_generated_voice_take(self.audio, 48000)
        self.assertEqual(self.media.read_voice_origin(generated)["origin"], "ai_generated")
        imported = self.media.import_voice_take(self.audio, 48000)
        self.assertEqual(imported, generated)
        self.assertIsNone(self.media.read_voice_origin(generated))
        # Replaying the same generated bytes must not restore the AI label.
        self.assertEqual(self.media.import_generated_voice_take(self.audio, 48000), generated)
        self.assertIsNone(self.media.read_voice_origin(generated))
        self.assertEqual(self.media.resolve(generated)[1], 48000)

    def test_generation_reimport_same_bytes_retains_origin_before_any_import(self):
        first = self.media.import_generated_voice_take(self.audio, 48000)
        second = self.media.import_generated_voice_take(self.audio, 48000)
        self.assertEqual(first, second)
        self.assertEqual(self.media.read_voice_origin(first)["origin"], "ai_generated")
        self.assertFalse((self.media.voice_root / (
            first[len("voice_"):] + ".origin-ambiguous")).exists())

    def test_tampered_voice_origin_and_media_fail_closed(self):
        asset_id = self.media.import_generated_voice_take(self.audio, 48000)
        origin_path = self.media.voice_root / (asset_id[len("voice_"):] + ".origin.json")
        self.assertIsNotNone(self.media.read_voice_origin(asset_id))
        origin_path.write_text('{"origin": "human_capture"}', encoding="utf-8")
        self.assertIsNone(self.media.read_voice_origin(asset_id))
        # Re-generation may still reuse the playable bytes, but the origin
        # stays quarantined even if someone removes the bad sidecar later.
        self.assertEqual(self.media.import_generated_voice_take(self.audio, 48000), asset_id)
        self.assertIsNone(self.media.read_voice_origin(asset_id))
        origin_path.unlink()
        self.assertEqual(self.media.import_generated_voice_take(self.audio, 48000), asset_id)
        self.assertIsNone(self.media.read_voice_origin(asset_id))
        # Tampering the underlying WAV also fails the media integrity check.
        media_path = self.media.voice_root / (asset_id[len("voice_"):] + ".wav")
        with media_path.open("ab") as output:
            output.write(b"altered")
        self.assertIsNone(self.media.read_voice_origin(asset_id))

    def test_sound_asset_resolves_only_verified_master(self):
        asset = self.sounds.add(self.audio, 48000, "Ocean", "procedural", loop=False)
        resolved, rate = self.media.resolve("sound_" + asset.id)
        self.assertEqual((len(resolved), rate), (4800, 48000))
        path = Path(self.sounds.path(asset))
        with path.open("ab") as output:
            output.write(b"tamper")
        with self.assertRaisesRegex(ValueError, "checksum mismatch"):
            self.media.resolve("sound_" + asset.id)

    def test_missing_unknown_and_unsafe_references_fail(self):
        for asset_id in ("../../etc/passwd", "voice_../evil", "sound_missing", "voice_notahash"):
            with self.subTest(asset_id=asset_id), self.assertRaisesRegex(ValueError, "Unknown project asset namespace"):
                self.media.resolve(asset_id)
        with self.assertRaises(FileNotFoundError):
            self.media.resolve("voice_" + "0" * 64)
        with self.assertRaises(FileNotFoundError):
            self.media.resolve("sound_" + "0" * 12)

    def test_reject_metadata_path_escape(self):
        asset = self.sounds.add(self.audio, 48000, "Ocean", "procedural", loop=False)
        asset.file = "../secrets.wav"
        with self.assertRaisesRegex(ValueError, "Unsafe Sound Library filename"):
            self.media.resolve("sound_" + asset.id)

    def test_sound_library_forged_path_cannot_read_export_or_delete_other_files(self):
        import unittest.mock

        first = self.sounds.add(self.audio, 48000, "First", "procedural", False)
        second = self.sounds.add(self.audio * 0.9, 48000, "Second", "procedural", False)
        second_path = Path(self.sounds.path(second))
        original_second_bytes = second_path.read_bytes()
        first.file = "../outside.wav"
        with unittest.mock.patch(
                "this_voice_thing.core.soundscape.assets._sha256",
                side_effect=AssertionError("unsafe hash read")):
            self.assertFalse(self.sounds.verify(first))
        with self.assertRaisesRegex(ValueError, "Unsafe Sound Library filename"):
            self.sounds.path(first)
        with self.assertRaisesRegex(ValueError, "path or checksum"):
            self.sounds.export(first.id, self.root / "bad")
        with self.assertRaisesRegex(ValueError, "Unsafe Sound Library filename"):
            self.media.resolve("sound_" + first.id)
        self.assertTrue(self.sounds.remove(first.id))
        self.assertEqual(second_path.read_bytes(), original_second_bytes)

    def test_forged_sound_index_cannot_repoint_to_another_valid_asset(self):
        first = self.sounds.add(self.audio, 48000, "First", "procedural", False)
        second = self.sounds.add(self.audio * 0.5, 48000, "Second", "procedural", False)
        first.file = second.file
        first.sha256 = second.sha256
        self.assertFalse(self.sounds.verify(first))
        with self.assertRaisesRegex(ValueError, "Unsafe Sound Library filename"):
            self.media.resolve("sound_" + first.id)
        with self.assertRaisesRegex(ValueError, "path or checksum"):
            self.sounds.export(first.id, self.root / "repointed")
        self.assertFalse((self.root / "repointed.wav").exists())

    def test_voice_tamper_is_detected_and_never_overwritten(self):
        identifier = self.media.import_voice_take(self.audio, 48000)
        target = self.media.voice_root / (identifier[6:] + ".wav")
        with target.open("ab") as output:
            output.write(b"tamper")
        with self.assertRaisesRegex(ValueError, "checksum mismatch"):
            self.media.resolve(identifier)
        with self.assertRaisesRegex(ValueError, "does not match"):
            self.media.import_voice_take(self.audio, 48000)

    def test_invalid_pcm_never_persists(self):
        with self.assertRaises(ValueError):
            self.media.import_voice_take([float("nan")], 48000)
        self.assertFalse(self.media.voice_root.exists())


if __name__ == "__main__":
    unittest.main()
